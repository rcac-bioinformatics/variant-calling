#!/usr/bin/env python3
"""make_staged_manifest.py: write the manifest of a staged copy: every directory and file under
DIR with its size and md5, so check_staged.sh can verify the copy on Depot later.

Usage: python3 make_staged_manifest.py DIR OUT.tsv --note "where the files came from"
                                        [--exclude GLOB ...]
Run on the staging build (restage.sh does), or on a finished results copy (regen_results.sh).
Symbolic links are refused: a staged copy must hold real files. Python 3.6.
Columns: path, type (dir|file), bytes, md5, need, source.
"""
import argparse
import fnmatch
import hashlib
import os
import sys


def md5(p):
    h = hashlib.md5()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("out")
    ap.add_argument("--note", required=True)
    ap.add_argument("--exclude", action="append", default=[])
    a = ap.parse_args()
    root = os.path.abspath(a.dir)
    if not os.path.isdir(root):
        sys.exit("%s is not a directory" % root)
    rows, links = [], []
    for d, dirs, files in os.walk(root):
        dirs.sort()
        rel_d = os.path.relpath(d, root)
        for name in dirs:
            rel = os.path.normpath(os.path.join(rel_d, name))
            if any(fnmatch.fnmatch(rel, g) for g in a.exclude):
                continue
            if os.path.islink(os.path.join(d, name)):
                links.append(rel)
                continue
            rows.append("%s\tdir\t-\t-\trequired\t%s" % (rel, a.note))
        for name in sorted(files):
            p = os.path.join(d, name)
            rel = os.path.normpath(os.path.join(rel_d, name))
            if any(fnmatch.fnmatch(rel, g) for g in a.exclude):
                continue
            if os.path.islink(p):
                links.append(rel)
                continue
            rows.append("%s\tfile\t%d\t%s\trequired\t%s" % (rel, os.path.getsize(p), md5(p), a.note))
    if links:
        sys.exit("symbolic links in %s (a staged copy must hold real files):\n  %s" % (root, "\n  ".join(links)))
    # dirs excluded by a glob also hide their content
    keep = []
    for r in rows:
        p = r.split("\t", 1)[0]
        if not any(fnmatch.fnmatch(p, g.rstrip("/") + "/*") for g in a.exclude):
            keep.append(r)
    head = ["# Expected content of %s. Generated by make_staged_manifest.py; do not edit." % root,
            "# Anything else in the staged copy is an error (check_staged.sh).",
            "path\ttype\tbytes\tmd5\tneed\tsource"]
    with open(a.out, "w") as o:
        o.write("\n".join(head + keep) + "\n")
    nf = sum(1 for r in keep if "\tfile\t" in r)
    sys.stderr.write("wrote %s: %d files, %d directories\n" % (a.out, nf, len(keep) - nf))


if __name__ == "__main__":
    main()
